export const messagesByLocale: Record<UiLocale, Record<MessageKey, string>> = {
  "zh-CN": zhCNMessages,
  "en-US": enUSMessages,
};

export function formatMessage(
  locale: UiLocale,
  key: MessageKey,
  values: Readonly<Record<string, string | number>> = {},
): string {
  return messagesByLocale[locale][key].replace(/\{(\w+)\}/g, (_match, name: string) =>
    Object.hasOwn(values, name) ? String(values[name]) : `{${name}}`,
  );
}


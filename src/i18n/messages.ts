export function translateRuntimeText(locale: UiLocale, text: string): string {
  if (locale === "zh-CN") return text;
  const written = /^(.+) 已写入；(原标签页已关闭|原保存目标已变化)，可从该文件恢复。$/.exec(text);
  if (written) {
    const change = written[2] === "原标签页已关闭"
      ? "the original tab was closed"
      : "the original save target changed";
    return `${written[1]} was written; ${change}. You can recover from that file.`;
  }
  return englishRuntimeText[text] ?? text;
}
